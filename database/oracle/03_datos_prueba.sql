FUNCTION siguiente_id(p_tabla VARCHAR2,p_columna VARCHAR2) RETURN NUMBER IS
v_max NUMBER; v_siguiente NUMBER; v_seq VARCHAR2(40);
BEGIN
EXECUTE IMMEDIATE 'SELECT NVL(MAX('||p_columna||'),0) FROM SMCFT.'||p_tabla INTO v_max;
v_seq := CASE p_tabla
WHEN 'PERSONA' THEN 'SEQ_PERSONA'
WHEN 'VEHICULO' THEN 'SEQ_VEHICULO'
WHEN 'DOCUMENTO' THEN 'SEQ_DOCUMENTO'
WHEN 'PASO_FRONTERIZO' THEN 'SEQ_PASO'
WHEN 'CRUCE_FRONTERIZO' THEN 'SEQ_CRUCE'
WHEN 'CATEGORIA_ITEM' THEN 'SEQ_CATEGORIA'
WHEN 'DECLARACION' THEN 'SEQ_DECLARACION'
WHEN 'ITEM_DECLARADO' THEN 'SEQ_ITEM'
WHEN 'PLAZO_ADMISION' THEN 'SEQ_PLAZO'
WHEN 'AUTORIZACION_MENOR' THEN 'SEQ_AUTORIZACION'
WHEN 'REPORTE' THEN 'SEQ_REPORTE'
WHEN 'REPORTE_DETALLE' THEN 'SEQ_REPORTE_DET'
WHEN 'AUDITORIA' THEN 'SEQ_AUDITORIA'
WHEN 'AUDITORIA_DETALLE' THEN 'SEQ_AUDITORIA_DET'
WHEN 'USUARIO' THEN 'SEQ_USUARIO'
ELSE NULL END;
IF v_seq IS NULL THEN RETURN v_max+1; END IF;
LOOP
EXECUTE IMMEDIATE 'SELECT SMCFT.'||v_seq||'.NEXTVAL FROM DUAL' INTO v_siguiente;
EXIT WHEN v_siguiente>v_max;
END LOOP;
RETURN v_siguiente;
END;
PROCEDURE documento(p_numero VARCHAR2,p_tipo VARCHAR2,p_persona NUMBER,
p_vehiculo NUMBER,p_id OUT NUMBER) IS
v_duenio NUMBER; v_auto NUMBER;
BEGIN
SELECT MIN(ID_DOCUMENTO) INTO p_id FROM SMCFT.DOCUMENTO WHERE NUMERO=p_numero;
IF p_id IS NULL THEN
p_id:=siguiente_id('DOCUMENTO','ID_DOCUMENTO');
INSERT INTO SMCFT.DOCUMENTO
(ID_DOCUMENTO,TIPO_DOCUMENTO,NUMERO,FECHA_EMISION,FECHA_VENCIMIENTO,
ID_PERSONA,ID_VEHICULO,ESTADO)
VALUES(p_id,p_tipo,p_numero,TRUNC(SYSDATE)-365,ADD_MONTHS(TRUNC(SYSDATE),120),
p_persona,p_vehiculo,'VIGENTE');
ELSE
