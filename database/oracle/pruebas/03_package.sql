SET SERVEROUTPUT ON SIZE UNLIMITED
SET DEFINE OFF
DECLARE v_paso NUMBER; v_cruce NUMBER; v_n NUMBER;
BEGIN
SAVEPOINT demo;
SELECT MIN(ID_PASO) INTO v_paso FROM SMCFT.PASO_FRONTERIZO WHERE NOMBRE='Los Libertadores';
IF v_paso IS NULL THEN
RAISE_APPLICATION_ERROR(-20030, 'No existe el paso Los Libertadores.');
END IF;
SMCFT.PKG_GESTION_FRONTERA.sp_registrar_cruce(v_paso,'ABCD12','SALIDA',
SMCFT.PKG_GESTION_FRONTERA.t_ruts_varray('12345678-9'),'12345678-9',v_cruce);
SELECT COUNT(*) INTO v_n FROM SMCFT.DETALLE_CRUCE_PERSONA WHERE ID_CRUCE=v_cruce;
IF v_n <> 1 THEN RAISE_APPLICATION_ERROR(-20905,'Viajeros incorrectos'); END IF;
DBMS_OUTPUT.PUT_LINE('OK: procedimiento publico del package registro cruce '||v_cruce);
ROLLBACK TO demo;
EXCEPTION WHEN OTHERS THEN ROLLBACK TO demo; RAISE;
END;
/
