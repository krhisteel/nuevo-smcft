SET SERVEROUTPUT ON SIZE UNLIMITED
SET DEFINE OFF
DECLARE
v_paso NUMBER; v_vehiculo NUMBER; v_cruce NUMBER; v_dias NUMBER;
BEGIN
SAVEPOINT demo;
SELECT MIN(ID_PASO) INTO v_paso FROM SMCFT.PASO_FRONTERIZO WHERE NOMBRE = 'Los Libertadores';
IF v_paso IS NULL THEN
RAISE_APPLICATION_ERROR(-20030, 'No existe el paso Los Libertadores.');
END IF;
SELECT ID_VEHICULO INTO v_vehiculo FROM SMCFT.VEHICULO WHERE PATENTE = 'ABCD12';
INSERT INTO
SMCFT.CRUCE_FRONTERIZO(ID_CRUCE,ID_PASO,ID_VEHICULO,TIPO_MOVIMIENTO,FECHA_HORA,ESTADO)
VALUES(SMCFT.SEQ_CRUCE.NEXTVAL,v_paso,v_vehiculo,'SALIDA',SYSTIMESTAMP,'AUTORIZADO')
RETURNING ID_CRUCE INTO v_cruce;
SELECT CAST(FECHA_LIMITE AS DATE)-CAST(FECHA_INGRESO AS DATE) INTO v_dias
FROM SMCFT.PLAZO_ADMISION WHERE ID_CRUCE_INGRESO=v_cruce;
IF v_dias <> 180 THEN RAISE_APPLICATION_ERROR(-20901,'Plazo incorrecto'); END IF;
DBMS_OUTPUT.PUT_LINE('OK: trigger de fila creo plazo de 180 dias sin llamar al package.');
ROLLBACK TO demo;
EXCEPTION WHEN OTHERS THEN ROLLBACK TO demo; RAISE;
END;
/
