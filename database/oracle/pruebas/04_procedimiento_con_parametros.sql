SET SERVEROUTPUT ON SIZE UNLIMITED
SET DEFINE OFF
DECLARE v_id NUMBER; v_n NUMBER;
BEGIN
SAVEPOINT demo;
SMCFT.SP_REPORTE_CRUCES(TRUNC(SYSDATE)-1,TRUNC(SYSDATE)+1,1,v_id);
SELECT COUNT(*) INTO v_n FROM SMCFT.REPORTE_DETALLE WHERE ID_REPORTE=v_id;
IF v_n=0 THEN RAISE_APPLICATION_ERROR(-20906,'Reporte sin detalle'); END IF;
DBMS_OUTPUT.PUT_LINE('OK: reporte '||v_id||' generado; detalles: '||v_n);
ROLLBACK TO demo;
EXCEPTION WHEN OTHERS THEN ROLLBACK TO demo; RAISE;
END;
/
