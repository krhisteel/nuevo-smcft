SET SERVEROUTPUT ON SIZE UNLIMITED
SET DEFINE OFF
DECLARE
v_paso NUMBER; v_vehiculo NUMBER; v_cruce NUMBER; v_decl NUMBER; v_cat NUMBER; v_total NUMBER;
BEGIN
SAVEPOINT demo;
SELECT MIN(ID_PASO) INTO v_paso FROM SMCFT.PASO_FRONTERIZO WHERE NOMBRE = 'Los Libertadores';
IF v_paso IS NULL THEN
RAISE_APPLICATION_ERROR(-20030, 'No existe el paso Los Libertadores.');
END IF;
SELECT ID_VEHICULO INTO v_vehiculo FROM SMCFT.VEHICULO WHERE PATENTE = 'ABCD12';
INSERT INTO
SMCFT.CRUCE_FRONTERIZO(ID_CRUCE,ID_PASO,ID_VEHICULO,TIPO_MOVIMIENTO,FECHA_HORA,ESTADO)
VALUES(SMCFT.SEQ_CRUCE.NEXTVAL,v_paso,v_vehiculo,'SALIDA',SYSTIMESTAMP,'AUTORIZADO')
RETURNING ID_CRUCE INTO v_cruce;
SELECT ID_CATEGORIA INTO v_cat FROM SMCFT.CATEGORIA_ITEM WHERE NOMBRE='ELECTRONICA';
INSERT INTO SMCFT.DECLARACION(ID_DECLARACION,ID_CRUCE,TIPO,FECHA,ESTADO)
VALUES(SMCFT.SEQ_DECLARACION.NEXTVAL,v_cruce,'EQUIPAJE',SYSDATE,'REGISTRADA') RETURNING
ID_DECLARACION INTO v_decl;
INSERT INTO SMCFT.ITEM_DECLARADO VALUES(SMCFT.SEQ_ITEM.NEXTVAL,v_decl,v_cat,'Notebook demo',1,450,'S');
SELECT SMCFT.FN_VALOR_DECLARADO(v_cruce) INTO v_total FROM DUAL;
IF v_total<>450 THEN RAISE_APPLICATION_ERROR(-20908,'Valor incorrecto'); END IF;
DBMS_OUTPUT.PUT_LINE('OK: funcion invocada desde SQL devolvio USD '||v_total);
ROLLBACK TO demo;
EXCEPTION WHEN OTHERS THEN ROLLBACK TO demo; RAISE;
END;
/
