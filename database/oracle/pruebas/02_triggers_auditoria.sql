SET SERVEROUTPUT ON SIZE UNLIMITED
SET DEFINE OFF
DECLARE v_antes NUMBER; v_despues NUMBER; v_filas NUMBER; v_sent NUMBER;
BEGIN
SAVEPOINT demo;
SELECT COUNT(*) INTO v_antes FROM SMCFT.AUDITORIA_DETALLE;
SELECT COUNT(*) INTO v_sent FROM SMCFT.AUDITORIA WHERE TIPO_AUDITORIA='TRIGGER_SENTENCIA';
UPDATE SMCFT.DOCUMENTO SET ESTADO='REVISADO' WHERE ID_DOCUMENTO IN (1,2);
v_filas := SQL%ROWCOUNT;
IF v_filas <> 2 THEN RAISE_APPLICATION_ERROR(-20902,'Deben existir documentos 1 y 2'); END IF;
SELECT COUNT(*) INTO v_despues FROM SMCFT.AUDITORIA_DETALLE;
IF v_despues-v_antes <> 2 THEN RAISE_APPLICATION_ERROR(-20903,'Auditoria de fila incorrecta'); END
IF;
SELECT COUNT(*)-v_sent INTO v_despues FROM SMCFT.AUDITORIA WHERE
TIPO_AUDITORIA='TRIGGER_SENTENCIA';
IF v_despues <> 1 THEN RAISE_APPLICATION_ERROR(-20904,'Auditoria de sentencia incorrecta'); END IF;
DBMS_OUTPUT.PUT_LINE('OK: 1 UPDATE, 2 documentos, 2 detalles de fila y 1 auditoria de sentencia.');
ROLLBACK TO demo;
EXCEPTION WHEN OTHERS THEN ROLLBACK TO demo; RAISE;
END;
/
