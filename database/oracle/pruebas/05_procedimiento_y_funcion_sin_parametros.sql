SET SERVEROUTPUT ON SIZE UNLIMITED
SET DEFINE OFF
DECLARE
v_paso NUMBER; v_vehiculo NUMBER; v_cruce NUMBER; v_total NUMBER; v_antes NUMBER; v_estado
VARCHAR2(20);
BEGIN
SAVEPOINT demo;
SELECT MIN(ID_PASO) INTO v_paso FROM SMCFT.PASO_FRONTERIZO WHERE NOMBRE = 'Los Libertadores';
IF v_paso IS NULL THEN
RAISE_APPLICATION_ERROR(-20030, 'No existe el paso Los Libertadores.');
END IF;
SELECT ID_VEHICULO INTO v_vehiculo FROM SMCFT.VEHICULO WHERE PATENTE = 'ABCD12';
INSERT INTO
SMCFT.CRUCE_FRONTERIZO(ID_CRUCE,ID_PASO,ID_VEHICULO,TIPO_MOVIMIENTO,FECHA_HORA,ESTADO)
VALUES(SMCFT.SEQ_CRUCE.NEXTVAL,v_paso,v_vehiculo,'SALIDA',SYSTIMESTAMP,'AUTORIZADO')
RETURNING ID_CRUCE INTO v_cruce;
UPDATE SMCFT.PLAZO_ADMISION SET FECHA_LIMITE=CAST(TRUNC(SYSDATE)-1 AS TIMESTAMP)
WHERE ID_CRUCE_INGRESO=v_cruce;
SELECT SMCFT.FN_TOTAL_PLAZOS_VENCIDOS() INTO v_antes FROM DUAL;
SMCFT.SP_ACTUALIZAR_PLAZOS;
SELECT ESTADO INTO v_estado FROM SMCFT.PLAZO_ADMISION WHERE ID_CRUCE_INGRESO=v_cruce;
IF v_estado <> 'VENCIDO' OR v_antes < 1 THEN RAISE_APPLICATION_ERROR(-20907,'Actualizacion incorrecta'); END IF;
DBMS_OUTPUT.PUT_LINE('OK: funcion sin parametros detecto '||v_antes||' plazos; procedimiento marco VENCIDO.');
ROLLBACK TO demo;
EXCEPTION WHEN OTHERS THEN ROLLBACK TO demo; RAISE;
END;
/
