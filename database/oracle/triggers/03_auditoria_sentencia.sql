CREATE OR REPLACE TRIGGER SMCFT.TRG_DOCUMENTO_SENTENCIA
AFTER INSERT OR UPDATE OR DELETE ON SMCFT.DOCUMENTO
DECLARE
v_accion VARCHAR2(20);
BEGIN
IF INSERTING THEN v_accion := 'INSERT';
ELSIF UPDATING THEN v_accion := 'UPDATE';
ELSE v_accion := 'DELETE'; END IF;
INSERT INTO SMCFT.AUDITORIA
(ID_AUDITORIA, ID_USUARIO_AUDITOR, TIPO_AUDITORIA, ENTIDAD, ENTIDAD_ID,
DESCRIPCION, ESTADO, FECHA_INICIO, FECHA_CIERRE)
VALUES (SMCFT.SEQ_AUDITORIA.NEXTVAL, 1, 'TRIGGER_SENTENCIA', 'DOCUMENTO', NULL,
'Sentencia ' || v_accion || '; sesion Oracle: ' || SYS_CONTEXT('USERENV','SESSION_USER'),
'COMPLETADA', SYSTIMESTAMP, SYSTIMESTAMP);
END;
/
