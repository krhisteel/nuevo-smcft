CREATE OR REPLACE TRIGGER SMCFT.TRG_CRUCE_PLAZO_AI
AFTER INSERT ON SMCFT.CRUCE_FRONTERIZO
FOR EACH ROW
WHEN (NEW.ID_VEHICULO IS NOT NULL AND NEW.TIPO_MOVIMIENTO = 'SALIDA')
DECLARE
v_tipo_vehiculo SMCFT.VEHICULO.TIPO_VEHICULO%TYPE;
v_dias NUMBER;
v_tipo_plazo VARCHAR2(30);
BEGIN
SELECT TIPO_VEHICULO INTO v_tipo_vehiculo
FROM SMCFT.VEHICULO
WHERE ID_VEHICULO = :NEW.ID_VEHICULO;
IF v_tipo_vehiculo = 'DIPLOMATICO' THEN
v_dias := 90;
v_tipo_plazo := 'DIPLOMATICO_90';
ELSE
v_dias := 180;
v_tipo_plazo := 'ADMISION_TEMPORAL_180';
END IF;
INSERT INTO SMCFT.PLAZO_ADMISION (
ID_PLAZO, ID_VEHICULO, ID_CRUCE_INGRESO, FECHA_INGRESO, FECHA_LIMITE,
TIPO, ESTADO, OBSERVACIONES
) VALUES (
SMCFT.SEQ_PLAZO.NEXTVAL, :NEW.ID_VEHICULO, :NEW.ID_CRUCE, :NEW.FECHA_HORA,
CAST(:NEW.FECHA_HORA AS DATE) + v_dias, v_tipo_plazo, 'ACTIVO',
'Generado automaticamente por TRG_CRUCE_PLAZO_AI'
);
EXCEPTION
WHEN NO_DATA_FOUND THEN
RAISE_APPLICATION_ERROR(-20004, 'Vehiculo inexistente al generar plazo.');
END TRG_CRUCE_PLAZO_AI;
/
