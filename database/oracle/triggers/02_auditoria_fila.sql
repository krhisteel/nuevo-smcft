CREATE OR REPLACE TRIGGER SMCFT.TRG_DOCUMENTO_AUDIT
AFTER INSERT OR UPDATE OR DELETE ON SMCFT.DOCUMENTO
FOR EACH ROW
DECLARE
v_id_auditoria SMCFT.AUDITORIA.ID_AUDITORIA%TYPE;
v_accion VARCHAR2(20);
v_id_documento SMCFT.DOCUMENTO.ID_DOCUMENTO%TYPE;
v_id_usuario_sistema CONSTANT NUMBER := 1; -- usuario "sistema" (ver 01_secuencias_datos_prueba.sql)
BEGIN
IF INSERTING THEN
v_accion := 'INSERT';
v_id_documento := :NEW.ID_DOCUMENTO;
ELSIF UPDATING THEN
v_accion := 'UPDATE';
v_id_documento := :NEW.ID_DOCUMENTO;
ELSE
v_accion := 'DELETE';
v_id_documento := :OLD.ID_DOCUMENTO;
END IF;
BEGIN
SELECT ID_AUDITORIA INTO v_id_auditoria
FROM SMCFT.AUDITORIA
WHERE ENTIDAD = 'DOCUMENTO' AND ESTADO = 'ABIERTA' AND ROWNUM = 1;
EXCEPTION
WHEN NO_DATA_FOUND THEN
INSERT INTO SMCFT.AUDITORIA (
ID_AUDITORIA, ID_USUARIO_AUDITOR, TIPO_AUDITORIA, ENTIDAD, ENTIDAD_ID,
DESCRIPCION, ESTADO, FECHA_INICIO, FECHA_CIERRE
) VALUES (
SMCFT.SEQ_AUDITORIA.NEXTVAL, v_id_usuario_sistema, 'AUTOMATICA_TRIGGER',
'DOCUMENTO', NULL,
'Auditoria automatica de cambios en la tabla DOCUMENTO', 'ABIERTA', SYSTIMESTAMP,
NULL
) RETURNING ID_AUDITORIA INTO v_id_auditoria;
END;
INSERT INTO SMCFT.AUDITORIA_DETALLE (
ID_DETALLE, ID_AUDITORIA, ACCION, DESCRIPCION, ID_USUARIO, RESULTADO, IP_ADDRESS,
FECHA_ACCION
) VALUES (
SMCFT.SEQ_AUDITORIA_DET.NEXTVAL, v_id_auditoria, v_accion,
'Operacion ' || v_accion || ' sobre SMCFT.DOCUMENTO.ID_DOCUMENTO=' || v_id_documento,
v_id_usuario_sistema, 'OK', NULL, SYSTIMESTAMP
);
END TRG_DOCUMENTO_AUDIT;
/
