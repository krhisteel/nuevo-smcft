SELECT OBJECT_NAME, OBJECT_TYPE, STATUS FROM USER_OBJECTS
WHERE STATUS = 'INVALID' ORDER BY OBJECT_TYPE, OBJECT_NAME;
SELECT NAME, TYPE, LINE, POSITION, TEXT FROM USER_ERRORS ORDER BY NAME, SEQUENCE;
DECLARE v_n NUMBER;
BEGIN
SELECT COUNT(*) INTO v_n FROM USER_OBJECTS WHERE STATUS = 'INVALID';
IF v_n > 0 THEN RAISE_APPLICATION_ERROR(-20090, 'Hay objetos invalidos: revise USER_ERRORS.'); END
IF;
DBMS_OUTPUT.PUT_LINE('No hay objetos invalidos en el esquema.');
END;
/
