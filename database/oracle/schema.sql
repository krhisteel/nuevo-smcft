-- ===================== USUARIOS =====================
CREATE TABLE users (
    id         NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rut        VARCHAR2(12)  NOT NULL UNIQUE,
    nombre     VARCHAR2(100) NOT NULL,
    email      VARCHAR2(150) NOT NULL UNIQUE,
    password   VARCHAR2(255) NOT NULL,
    rol        VARCHAR2(50)  NOT NULL,
    activo     NUMBER(1) DEFAULT 1 NOT NULL CHECK (activo IN (0, 1)),
    created_at TIMESTAMP    DEFAULT LOCALTIMESTAMP
);

CREATE TABLE user_roles (
    id          NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     NUMBER(10)     NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    rol         VARCHAR2(50) NOT NULL,
    asignado_at TIMESTAMP   DEFAULT LOCALTIMESTAMP,
    activo      NUMBER(1) DEFAULT 1 NOT NULL CHECK (activo IN (0, 1))
);

-- ===================== AUTENTICACIÓN =====================
CREATE TABLE token_blacklist (
    id            NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token         VARCHAR2(1000)         NOT NULL,
    email         VARCHAR2(150) NOT NULL,
    invalidado_at TIMESTAMP    DEFAULT LOCALTIMESTAMP
);

CREATE TABLE login_attempts (
    id                 NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email              VARCHAR2(150) NOT NULL,
    exitoso            NUMBER(1) NOT NULL CHECK (exitoso IN (0, 1)),
    ip_address         VARCHAR2(45),
    intento_at         TIMESTAMP    DEFAULT LOCALTIMESTAMP,
    token_blacklist_id NUMBER(10)      NULL REFERENCES token_blacklist(id) ON DELETE SET NULL
);

-- ===================== VEHÍCULOS =====================
CREATE TABLE vehicles (
    id              NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patente         VARCHAR2(10)  NOT NULL UNIQUE,
    marca           VARCHAR2(50)  NOT NULL,
    modelo          VARCHAR2(50)  NOT NULL,
    anio            NUMBER(10)      NOT NULL,
    tipo_vehiculo   VARCHAR2(30)  NOT NULL,
    rut_propietario VARCHAR2(12)  NOT NULL,
    estado          VARCHAR2(30) DEFAULT 'EN_TERRITORIO_NACIONAL' NOT NULL,
    created_at      TIMESTAMP    DEFAULT LOCALTIMESTAMP
);

CREATE TABLE vehicle_documents (
    id                NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id        NUMBER(10)     NOT NULL REFERENCES vehicles(id) ON DELETE CASCADE,
    tipo              VARCHAR2(50) NOT NULL,
    numero            VARCHAR2(50) NOT NULL UNIQUE,
    fecha_vencimiento DATE        NOT NULL,
    vigente           NUMBER(1) DEFAULT 1 NOT NULL CHECK (vigente IN (0, 1)),
    created_at        TIMESTAMP   DEFAULT LOCALTIMESTAMP
);

-- ===================== CATEGORÍAS DE ÍTEMS =====================
CREATE TABLE item_categories (
    id                   NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre               VARCHAR2(100)  NOT NULL UNIQUE,
    descripcion          VARCHAR2(500)  NOT NULL,
    requiere_declaracion NUMBER(1) DEFAULT 0 NOT NULL CHECK (requiere_declaracion IN (0, 1)),
    limite_valor_usd     NUMBER(10,2) NULL,
    activo               NUMBER(1) DEFAULT 1 NOT NULL CHECK (activo IN (0, 1)),
    created_at           TIMESTAMP     DEFAULT LOCALTIMESTAMP
);

CREATE TABLE items (
    id           NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoria_id NUMBER(10)      NOT NULL REFERENCES item_categories(id) ON DELETE CASCADE,
    nombre       VARCHAR2(100) NOT NULL,
    descripcion  VARCHAR2(300) NOT NULL,
    unidad       VARCHAR2(30) DEFAULT 'unidad' NOT NULL,
    activo       NUMBER(1) DEFAULT 1 NOT NULL CHECK (activo IN (0, 1)),
    created_at   TIMESTAMP    DEFAULT LOCALTIMESTAMP
);

-- ===================== INGRESOS =====================
CREATE TABLE entries (
    id               NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patente          VARCHAR2(10)  NOT NULL,
    rut_conductor    VARCHAR2(12)  NOT NULL,
    pais_origen      VARCHAR2(100) NOT NULL,
    paso_fronterizo  VARCHAR2(100) NOT NULL,
    fecha_ingreso    TIMESTAMP    NOT NULL,
    tipo_ingreso     VARCHAR2(30)  NOT NULL,
    estado           VARCHAR2(30) DEFAULT 'PENDIENTE' NOT NULL,
    rut_fiscalizador VARCHAR2(12)  NULL,
    observaciones    VARCHAR2(500) NULL,
    created_at       TIMESTAMP    DEFAULT LOCALTIMESTAMP
);

CREATE TABLE entry_items (
    id          NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_id    NUMBER(10)       NOT NULL REFERENCES entries(id) ON DELETE CASCADE,
    descripcion VARCHAR2(200)  NOT NULL,
    cantidad    NUMBER(10) DEFAULT 1 NOT NULL,
    valor_usd   NUMBER(10,2) DEFAULT 0 NOT NULL,
    aprobado    NUMBER(1) DEFAULT 0 NOT NULL CHECK (aprobado IN (0, 1)),
    created_at  TIMESTAMP     DEFAULT LOCALTIMESTAMP
);

-- ===================== CRUCES FRONTERIZOS =====================
CREATE TABLE border_crossings (
    id               NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patente          VARCHAR2(10)  NOT NULL,
    rut_conductor    VARCHAR2(12)  NOT NULL,
    pais_destino     VARCHAR2(100) NOT NULL,
    paso_fronterizo  VARCHAR2(100) NOT NULL,
    fecha_cruce      TIMESTAMP    NOT NULL,
    estado           VARCHAR2(30) DEFAULT 'PENDIENTE' NOT NULL,
    rut_fiscalizador VARCHAR2(12)  NULL,
    observaciones    VARCHAR2(500) NULL,
    created_at       TIMESTAMP    DEFAULT LOCALTIMESTAMP
);

CREATE TABLE border_crossing_items (
    id                 NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    border_crossing_id NUMBER(10)       NOT NULL REFERENCES border_crossings(id) ON DELETE CASCADE,
    categoria_id       NUMBER(10)       NOT NULL,
    descripcion        VARCHAR2(200)  NOT NULL,
    cantidad           NUMBER(10) DEFAULT 1 NOT NULL,
    valor_usd          NUMBER(10,2) DEFAULT 0 NOT NULL,
    aprobado           NUMBER(1) DEFAULT 0 NOT NULL CHECK (aprobado IN (0, 1)),
    created_at         TIMESTAMP     DEFAULT LOCALTIMESTAMP
);

-- ===================== SANIDAD (SAG) =====================
CREATE TABLE sanitary_inspections (
    id               NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patente          VARCHAR2(10)  NOT NULL,
    rut_conductor    VARCHAR2(12)  NOT NULL,
    rut_inspector    VARCHAR2(12)  NOT NULL,
    paso_fronterizo  VARCHAR2(100) NOT NULL,
    fecha_inspeccion TIMESTAMP    NOT NULL,
    resultado        VARCHAR2(30) DEFAULT 'PENDIENTE' NOT NULL,
    observaciones    VARCHAR2(500) NULL,
    created_at       TIMESTAMP    DEFAULT LOCALTIMESTAMP
);

CREATE TABLE sanitary_items (
    id             NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inspection_id  NUMBER(10)      NOT NULL REFERENCES sanitary_inspections(id) ON DELETE CASCADE,
    descripcion    VARCHAR2(200) NOT NULL,
    resultado_item VARCHAR2(30) DEFAULT 'PENDIENTE' NOT NULL,
    observaciones  VARCHAR2(300) NULL,
    created_at     TIMESTAMP    DEFAULT LOCALTIMESTAMP
);

-- ===================== PLAZOS (DEADLINES) =====================
CREATE TABLE deadlines (
    id            NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patente       VARCHAR2(10)  NOT NULL,
    rut_conductor VARCHAR2(12)  NOT NULL,
    entry_id      NUMBER(10)      NOT NULL,
    fecha_ingreso TIMESTAMP    NOT NULL,
    fecha_limite  TIMESTAMP    NOT NULL,
    tipo          VARCHAR2(50)  NOT NULL,
    estado        VARCHAR2(30) DEFAULT 'ACTIVO' NOT NULL,
    observaciones VARCHAR2(500) NULL,
    created_at    TIMESTAMP    DEFAULT LOCALTIMESTAMP
);

CREATE TABLE deadline_alerts (
    id             NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    deadline_id    NUMBER(10)      NOT NULL REFERENCES deadlines(id) ON DELETE CASCADE,
    mensaje        VARCHAR2(500) NOT NULL,
    dias_restantes NUMBER(10)      NOT NULL,
    tipo_alerta    VARCHAR2(30)  NOT NULL,
    enviada        NUMBER(1) DEFAULT 0 NOT NULL CHECK (enviada IN (0, 1)),
    created_at     TIMESTAMP    DEFAULT LOCALTIMESTAMP
);

-- ===================== TRANSACCIONES =====================
CREATE TABLE transactions (
    id            NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rut_usuario   VARCHAR2(12)   NOT NULL,
    tipo          VARCHAR2(50)   NOT NULL,
    monto_total   NUMBER(12,2) NOT NULL,
    estado        VARCHAR2(30) DEFAULT 'PENDIENTE' NOT NULL,
    descripcion   VARCHAR2(500)  NOT NULL,
    referencia    VARCHAR2(100)  NULL,
    created_at    TIMESTAMP     DEFAULT LOCALTIMESTAMP,
    completada_at TIMESTAMP     NULL
);

CREATE TABLE transaction_details (
    id             NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id NUMBER(10)       NOT NULL REFERENCES transactions(id) ON DELETE CASCADE,
    concepto       VARCHAR2(200)  NOT NULL,
    monto          NUMBER(12,2) NOT NULL,
    cantidad       NUMBER(10) DEFAULT 1 NOT NULL,
    tipo_detalle   VARCHAR2(30) DEFAULT 'COBRO' NOT NULL,
    created_at     TIMESTAMP     DEFAULT LOCALTIMESTAMP
);

-- ===================== REPORTES =====================
CREATE TABLE reports (
    id            NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo        VARCHAR2(200) NOT NULL,
    tipo_reporte  VARCHAR2(50)  NOT NULL,
    fecha_inicio  TIMESTAMP    NOT NULL,
    fecha_fin     TIMESTAMP    NOT NULL,
    generado_por  VARCHAR2(12)  NOT NULL,
    estado        VARCHAR2(30) DEFAULT 'GENERANDO' NOT NULL,
    observaciones VARCHAR2(500) NULL,
    created_at    TIMESTAMP    DEFAULT LOCALTIMESTAMP
);

CREATE TABLE report_details (
    id          NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id   NUMBER(10)       NOT NULL REFERENCES reports(id) ON DELETE CASCADE,
    descripcion VARCHAR2(300)  NOT NULL,
    valor       NUMBER(10,2) DEFAULT 0 NOT NULL,
    unidad      VARCHAR2(50) DEFAULT 'unidad' NOT NULL,
    categoria   VARCHAR2(100)  NOT NULL,
    created_at  TIMESTAMP     DEFAULT LOCALTIMESTAMP
);

-- ===================== NOTIFICACIONES =====================
CREATE TABLE notifications (
    id                NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo            VARCHAR2(200) NOT NULL,
    mensaje           VARCHAR2(500) NOT NULL,
    tipo              VARCHAR2(50)  NOT NULL,
    deadline_alert_id NUMBER(10)      NULL,
    estado            VARCHAR2(30) DEFAULT 'PENDIENTE' NOT NULL,
    created_at        TIMESTAMP    DEFAULT LOCALTIMESTAMP,
    enviada_at        TIMESTAMP    NULL
);

CREATE TABLE notification_recipients (
    id               NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notification_id  NUMBER(10)      NOT NULL REFERENCES notifications(id) ON DELETE CASCADE,
    rut_destinatario VARCHAR2(12)  NOT NULL,
    email            VARCHAR2(150) NOT NULL,
    nombre           VARCHAR2(100) NOT NULL,
    leida            NUMBER(1) DEFAULT 0 NOT NULL CHECK (leida IN (0, 1)),
    leida_at         TIMESTAMP    NULL,
    created_at       TIMESTAMP    DEFAULT LOCALTIMESTAMP
);

-- ===================== AUDITORÍA =====================
CREATE TABLE audits (
    id             NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rut_auditor    VARCHAR2(12)  NOT NULL,
    tipo_auditoria VARCHAR2(50)  NOT NULL,
    entidad        VARCHAR2(100) NOT NULL,
    entidad_id     NUMBER(10)      NULL,
    descripcion    VARCHAR2(500) NOT NULL,
    estado         VARCHAR2(30) DEFAULT 'EN_PROCESO' NOT NULL,
    fecha_inicio   TIMESTAMP    NOT NULL,
    fecha_cierre   TIMESTAMP    NULL,
    created_at     TIMESTAMP    DEFAULT LOCALTIMESTAMP
);

CREATE TABLE audit_details (
    id           NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    audit_id     NUMBER(10)      NOT NULL REFERENCES audits(id) ON DELETE CASCADE,
    accion       VARCHAR2(100) NOT NULL,
    descripcion  VARCHAR2(500) NOT NULL,
    rut_usuario  VARCHAR2(12)  NOT NULL,
    resultado    VARCHAR2(30) DEFAULT 'EXITOSO' NOT NULL,
    ip_address   VARCHAR2(45)  NULL,
    fecha_accion TIMESTAMP    NOT NULL,
    created_at   TIMESTAMP    DEFAULT LOCALTIMESTAMP
);

-- ===================== ÍNDICES =====================
CREATE INDEX idx_token_blacklist_token ON token_blacklist (token);
CREATE INDEX idx_vehicles_propietario  ON vehicles (rut_propietario);
CREATE INDEX idx_entries_patente       ON entries (patente);
CREATE INDEX idx_crossings_patente     ON border_crossings (patente);
CREATE INDEX idx_recipients_rut        ON notification_recipients (rut_destinatario);

